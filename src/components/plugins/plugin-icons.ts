export function resolvePluginIcon(name: string | undefined): LucideIcon {
  if (!name) return Puzzle;
  return ICONS[name.toLowerCase()] ?? Puzzle;
}

export const PLUGIN_ICON_NAMES = Object.keys(ICONS);
