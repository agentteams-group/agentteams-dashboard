/**
 * Icon whitelist for plugins.
 *
 * Plugins reference icons by name (manifest/contribution data crosses a
 * serialization boundary, so they cannot pass component references). The
 * host resolves names from this fixed list; unknown names fall back to the
 * puzzle piece.
 */

